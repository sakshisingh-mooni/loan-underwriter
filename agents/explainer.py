"""
agents/explainer.py
--------------------
Agent 6: Explainer

Generates a formal reason letter in both English and Hindi.

FIX — Async node incompatibility with graph.stream():
  The original was `async def explainer_node(...)`.
  LangGraph 1.x raises TypeError when an async node is called via the
  SYNCHRONOUS graph.stream() / graph.invoke() API:
    "No synchronous function provided to 'explainer'. Either initialize
     with a synchronous function or invoke via the async API."

  Verified against langgraph==1.2.4.

  Fix: Make the node sync and wrap asyncio.gather() inside asyncio.run().
  asyncio.run() creates a fresh event loop, runs the coroutine to
  completion, and tears it down — safe to call from a sync context
  (Streamlit runs in a sync thread by default).

  The parallel LLM calls are preserved — English and Hindi letters
  are still generated concurrently, cutting latency in half vs sequential.

  ADDITIONAL FIX — asyncio.run() inside a running event loop:
  asyncio.run() raises RuntimeError if called from pytest-asyncio, Jupyter,
  or any other context that already has a running event loop.

  How this guard actually works:
    Streamlit runs each script execution in a dedicated OS thread
    (ScriptRunner.scriptThread). That thread has NO event loop of its own —
    it is separate from Tornado's main-thread loop. So asyncio.get_running_loop()
    raises RuntimeError("no running event loop") inside the Streamlit thread,
    and asyncio.run() succeeds there.

    pytest-asyncio and Jupyter DO have a running loop on the calling thread,
    so asyncio.get_running_loop() succeeds, and we fall through to the
    ThreadPoolExecutor path where asyncio.run() runs in a fresh OS thread
    that has no parent loop.

  The net result: asyncio.run() is used in Streamlit (correct), and
  ThreadPoolExecutor is used in pytest-asyncio / Jupyter (also correct).

HINDI QUALITY VERIFICATION — deterministic Python checks:
  The Hindi letter is generated by prompting LLaMA 3.3-70B with a Hindi
  prompt. LLMs can produce grammatically plausible but factually wrong
  output (e.g. wrong decision word, untranslated placeholders, code-switching
  to English mid-sentence) without any external signal of failure.

  In a BFSI context the Hindi letter is a regulatory document under RBI's
  Fair Lending guidelines, so silent quality failures are not acceptable.

  Fix: after generating the Hindi letter, deterministic Python checks
  verify four properties without an extra LLM call:
    1. >= 30% of non-whitespace characters are Devanagari (Unicode U+0900–U+097F).
       This tolerates English names and financial terms (CIBIL, FOIR) mixed in
       naturally, while catching a fully-English accidental output (~0% ratio).
    2. The correct decision word appears (अनुमोदित / अस्वीकृत / समीक्षाधीन).
    3. No unreplaced {brace} template placeholders remain.
    4. No unreplaced [bracket] template placeholders remain.

  A name post-processing step runs BEFORE the quality check, replacing
  [आपका नाम] and common variants with the actual applicant name.
  This handles a recurring LLaMA 3.3-70B behaviour where the model outputs
  a template placeholder instead of substituting the name from the prompt.

  On failure, the fallback template is substituted. The fallback does not
  re-call the LLM (no latency added on the failure path).

  Why Python instead of LLM-as-judge:
    The LLM judge was consistently failing correct letters by inventing
    reasons not in the criteria (e.g. rejecting English proper nouns in
    signatures, insisting names be transliterated to Devanagari). Deterministic
    checks are reliable for these objective properties and remove the extra
    LLM call and rate-limit exposure.

  Interview note: "The explainer agent mirrors real regulatory requirements —
  RBI's Fair Lending guidelines require lenders to communicate rejection
  reasons clearly and in the applicant's preferred language."
"""
import asyncio
import concurrent.futures
import logging
